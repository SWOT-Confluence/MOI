def _as_reach_list(reach_ids: Sequence) -> List[str]:
    return [str(r) for r in reach_ids]


def _build_reach_index(reach_ids: Sequence) -> Dict[str, int]:
    return {str(r): i for i, r in enumerate(reach_ids)}


def _sword_row_index(sword_dict: dict) -> Dict[str, int]:
    return {str(int(r)): i for i, r in enumerate(sword_dict['reach_id'])}


def _get_sword_scalar(sword_dict: dict, sword_idx: Dict[str, int], reach: str, field: str, default=np.nan):
    try:
        return float(sword_dict[field][sword_idx[str(reach)]])
    except Exception:
        return default


def _build_upstream_contribs(
    reach_ids: Sequence,
    sword_dict: dict,
    junctions: Sequence[dict],
) -> Dict[str, List[Tuple[str, float]]]:
    """Return mapping downstream reach -> [(upstream reach, coefficient), ...].

    For normal confluences, coefficients are 1. For distributaries, the previous
    MOI logic partitions upstream flow by downstream width. This keeps that
    global-run compatible behavior while preserving sparse mass equations.
    """
    reach_list = _as_reach_list(reach_ids)
    reach_set = set(reach_list)
    sword_idx = _sword_row_index(sword_dict)
    up_contribs: Dict[str, List[Tuple[str, float]]] = {}

    if junctions:
        for junc in junctions:
            U = [str(u) for u in junc.get('upflows', []) if str(u) in reach_set and str(u) != '0']
            D = [str(d) for d in junc.get('downflows', []) if str(d) in reach_set and str(d) != '0']
            if not U or not D:
                continue

            widths = []
            for d in D:
                w = _get_sword_scalar(sword_dict, sword_idx, d, 'width', default=1.0)
                if not np.isfinite(w) or w <= 0:
                    w = 1.0
                widths.append(w)
            total_w = float(np.sum(widths))

            for idx, d in enumerate(D):
                p = widths[idx] / total_w if total_w > 0 else 1.0 / len(D)
                up_contribs.setdefault(d, [])
                for u in U:
                    up_contribs[d].append((u, float(p)))

    # Fallback: if some SWORD upstream links were not represented in junctions,
    # add them with coefficient 1.0.
    for reach in reach_list:
        if reach not in sword_idx:
            continue
        k = sword_idx[reach]
        try:
            n_up = int(sword_dict['n_rch_up'][k])
        except Exception:
            n_up = 0
        for j in range(n_up):
            try:
                up = str(int(sword_dict['rch_id_up'][j, k]))
            except Exception:
                continue
            if up == '0' or up not in reach_set:
                continue
            already = any(u == up for u, _ in up_contribs.get(reach, []))
            if not already:
                up_contribs.setdefault(reach, []).append((up, 1.0))

    return up_contribs


def assign_runoff_regions_by_prefix(reach_ids: Sequence, prefix_len: int = 6) -> Tuple[np.ndarray, List[str]]:
    """Assign runoff subregions using the first `prefix_len` digits of reach_id."""
    unique_regions: List[str] = []
    reach_regions: List[int] = []
    for reach in _as_reach_list(reach_ids):
        rid = str(reach)
        region = rid[:prefix_len] if len(rid) >= prefix_len else rid
        if region not in unique_regions:
            unique_regions.append(region)
        reach_regions.append(unique_regions.index(region))
    return np.asarray(reach_regions, dtype=int), unique_regions


def compute_delta_area_for_mass_rows(
    reach_ids: Sequence,
    sword_dict: dict,
    facc: np.ndarray,
    upstream_contribs: Dict[str, List[Tuple[str, float]]],
) -> np.ndarray:
    """Compute lateral drainage-area increment for each reach.

    For dependent reaches, delta_A = facc_current - weighted direct-upstream facc.
    For source reaches, this value is kept for diagnostics/prior construction but
    no mass row is built for them.
    """
    reach_list = _as_reach_list(reach_ids)
    reach_index = _build_reach_index(reach_list)
    delta_A = np.zeros(len(reach_list), dtype=float)

    for i, reach in enumerate(reach_list):
        fcur = float(facc[i]) if np.isfinite(facc[i]) else 0.0
        upstream_area = 0.0
        for up, coeff in upstream_contribs.get(reach, []):
            j = reach_index.get(str(up))
            if j is not None and np.isfinite(facc[j]):
                upstream_area += float(coeff) * float(facc[j])
        delta_A[i] = max(0.0, fcur - upstream_area)
    return delta_A


def compute_runoff_priors(
    Qbar: np.ndarray,
    facc: np.ndarray,
    reach_regions: np.ndarray,
    u_conversion: float,
    min_runoff: float = 1.0,
    fallback_runoff: float = 315.36,
) -> np.ndarray:
    """Compute regional runoff pseudo-observations from Q/facc.

    Units: Q [m3/s], facc [km2], u_conversion [m3/s per km2 per mm/yr],
    so R [mm/yr] = Q / (facc * u_conversion).
    """
    K = int(np.max(reach_regions)) + 1 if len(reach_regions) else 0
    R = np.full(K, np.nan, dtype=float)

    global_vals = []
    for i in range(len(Qbar)):
        if np.isfinite(Qbar[i]) and np.isfinite(facc[i]) and facc[i] > 0:
            val = float(Qbar[i]) / (float(facc[i]) * float(u_conversion))
            if np.isfinite(val) and val > 0:
                global_vals.append(val)

    global_fallback = float(np.nanmedian(global_vals)) if global_vals else fallback_runoff
    if not np.isfinite(global_fallback) or global_fallback <= 0:
        global_fallback = fallback_runoff

    for k in range(K):
        idx = np.where(reach_regions == k)[0]
        if idx.size == 0:
            R[k] = global_fallback
            continue

        facc_region = facc[idx]
        good_facc = facc_region[np.isfinite(facc_region) & (facc_region > 0)]
        facc_median = np.nanmedian(good_facc) if good_facc.size else np.inf

        valid = []
        for i in idx:
            if (
                np.isfinite(Qbar[i])
                and np.isfinite(facc[i])
                and facc[i] > 0
                and facc[i] <= facc_median
            ):
                valid.append(i)

        if not valid:
            valid = [i for i in idx if np.isfinite(Qbar[i]) and np.isfinite(facc[i]) and facc[i] > 0]

        vals = []
        for i in valid:
            val = float(Qbar[i]) / (float(facc[i]) * float(u_conversion))
            if np.isfinite(val) and val > 0:
                vals.append(val)

        R[k] = float(np.nanmedian(vals)) if vals else global_fallback
        if not np.isfinite(R[k]) or R[k] <= 0:
            R[k] = global_fallback

    return np.clip(R, min_runoff, np.inf)


def build_sparse_sfoi_problem(
    reach_ids: Sequence,
    sword_dict: dict,
    junctions: Sequence[dict],
    Qbar: np.ndarray,
    sigQ: np.ndarray,
    facc: np.ndarray,
    u_conversion: float,
    params_dict: Optional[dict] = None,
    prefix_len: int = 6,
) -> dict:
    """Build sparse SFOI observation matrix and dependent-reach mass constraints.

    Sparse formulation:
        x = [Q_1, ..., Q_n, R_1, ..., R_K]

    Observations:
        Q_i observed for all reaches, and R_k pseudo-observed for runoff regions.

    Mass constraints, only for dependent reaches:
        Q_i - sum_u c_ui Q_u - delta_A_i * u * R_region(i) = 0

    Source/headwater reaches intentionally do not receive a mass row; their Q_i
    remains an independent discharge degree of freedom, matching Q_ind in the
    paper's SFOI model.
    """
    params_dict = params_dict or {}
    reach_list = _as_reach_list(reach_ids)
    n = len(reach_list)
    Qbar = np.asarray(Qbar, dtype=float).reshape(n)
    sigQ = np.asarray(sigQ, dtype=float).reshape(n)
    facc = np.asarray(facc, dtype=float).reshape(n)

    reach_regions, region_labels = assign_runoff_regions_by_prefix(reach_list, prefix_len=prefix_len)
    K = len(region_labels)
    nvar = n + K

    upstream_contribs = _build_upstream_contribs(reach_list, sword_dict, junctions)
    delta_A = compute_delta_area_for_mass_rows(reach_list, sword_dict, facc, upstream_contribs)
    R_prior = compute_runoff_priors(Qbar, facc, reach_regions, u_conversion)

    # Observation matrix: first Q observations, then R pseudo-observations.
    I_q = sp.eye(n, nvar, format='csr')
    rows_R = np.arange(K)
    cols_R = n + np.arange(K)
    data_R = np.ones(K, dtype=float)
    A_R = sp.csr_matrix((data_R, (rows_R, cols_R)), shape=(K, nvar))
    A_obs = sp.vstack([I_q, A_R], format='csr')
    L_obs = np.concatenate([Qbar, R_prior])

    # Convert sigQ to coefficient of variation for multiplicative model.
    covQ = np.divide(sigQ, np.maximum(np.abs(Qbar), 1e-6), out=np.full(n, 1.0), where=np.isfinite(sigQ))
    covQ = np.asarray(covQ, dtype=float)
    covQ[~np.isfinite(covQ) | (covQ <= 0)] = params_dict.get('FLPE_Uncertainty', 0.6)
    covQ = np.clip(covQ, params_dict.get('SFOI_Min_CV', 0.02), params_dict.get('SFOI_Max_CV', 10.0))

    runoff_cv = params_dict.get('Runoff_Uncertainty', params_dict.get('SFOI_Runoff_Uncertainty', 0.5))
    covR = np.full(K, float(runoff_cv), dtype=float)
    cov_obs = np.concatenate([covQ, covR])

    # Equality-style mass rows are kept as diagnostics and can also be used as
    # Mike-style soft observation rows by appending them to A_obs. Their target
    # is zero, so a relative CV is not statistically meaningful. Encode an
    # explicit absolute sigma through the solver's multiplicative theta floor.
    theta_floor = max(float(params_dict.get('SFOI_Theta_Floor', 5.0)), 1.0e-6)
    legacy_mass_cv = float(
        params_dict.get('SFOI_Mass_CV', params_dict.get('SFOI_Soft_Mass_CV', 1.0))
    )
    soft_mass_sigma = float(
        params_dict.get('SFOI_Soft_Mass_Sigma', legacy_mass_cv * theta_floor)
    )
    if not np.isfinite(soft_mass_sigma) or soft_mass_sigma <= 0:
        raise ValueError('SFOI_Soft_Mass_Sigma must be finite and positive')
    mass_cov_at_floor = soft_mass_sigma / theta_floor

    # Equality constraints for dependent reaches only.
    reach_index = _build_reach_index(reach_list)
    eq_rows, eq_cols, eq_data = [], [], []
    eq_reach_indices: List[int] = []

    for i, reach in enumerate(reach_list):
        ups = upstream_contribs.get(reach, [])
        if not ups:
            # Source/independent reach: no mass constraint row.
            continue

        row = len(eq_reach_indices)
        eq_reach_indices.append(i)

        # + Q_i
        eq_rows.append(row)
        eq_cols.append(i)
        eq_data.append(1.0)

        # - sum coeff * Q_up
        for up, coeff in ups:
            j = reach_index.get(str(up))
            if j is None:
                continue
            eq_rows.append(row)
            eq_cols.append(j)
            eq_data.append(-float(coeff))

        # - delta_A * u * R_region
        reg = int(reach_regions[i])
        eq_rows.append(row)
        eq_cols.append(n + reg)
        eq_data.append(-float(delta_A[i]) * float(u_conversion))

    A_eq = sp.csr_matrix((eq_data, (eq_rows, eq_cols)), shape=(len(eq_reach_indices), nvar))
    b_eq = np.zeros(len(eq_reach_indices), dtype=float)

    A_sfoi = sp.vstack([A_obs, A_eq], format='csr') if A_eq.shape[0] > 0 else A_obs
    L_sfoi = np.concatenate([L_obs, np.zeros(A_eq.shape[0], dtype=float)])
    cov_sfoi = np.concatenate(
        [cov_obs, np.full(A_eq.shape[0], mass_cov_at_floor, dtype=float)]
    )

    # Nonnegative variables. Optional q minimum can be provided, but default is 0.
    q_min = float(params_dict.get('SFOI_Q_Min', 0.0))
    r_min = float(params_dict.get('SFOI_R_Min', 0.0))
    lb = np.concatenate([np.full(n, q_min), np.full(K, r_min)])
    ub = None

    # Starting point from observations.
    x0 = np.concatenate([np.clip(Qbar, max(q_min, 1e-6), np.inf), np.clip(R_prior, max(r_min, 1e-6), np.inf)])

    return {
        'A_obs': A_obs,
        'L_obs': L_obs,
        'cov_obs': cov_obs,
        'A_sfoi': A_sfoi,
        'L_sfoi': L_sfoi,
        'cov_sfoi': cov_sfoi,
        'A_eq': A_eq,
        'b_eq': b_eq,
        'lb': lb,
        'ub': ub,
        'x0': x0,
        'n_reaches': n,
        'K_regions': K,
        'region_labels': region_labels,
        'reach_regions': reach_regions,
        'delta_A': delta_A,
        'eq_reach_indices': np.asarray(eq_reach_indices, dtype=int),
        'upstream_contribs': upstream_contribs,
        'u_conversion': u_conversion,
        'R_prior': R_prior,
        'soft_mass_sigma': soft_mass_sigma,
    }


