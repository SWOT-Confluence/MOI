"""
Sparse SFOI math core rebuilt to follow Durand et al. SFOI statistical model.

Key design choice for global basins
----------------------------------
This module keeps a sparse x = [Q_all, R_regions] formulation for scalability,
but it does NOT force source/headwater reaches to be generated by runoff.
Mass conservation equality constraints are built only for reaches that have
upstream reaches inside the current basin/domain. Therefore source reaches keep
independent discharge degrees of freedom, matching the role of Q_ind in the
paper.

The solver implements:
  * sparse weighted least squares for discharge/runoff observations;
  * Mike-style soft mass-balance rows by default, while retaining optional hard
    equality constraints for experiments;
  * an inner robust reweighting loop for outliers, following the paper/code
    adjust_lsq.py logic;
  * an outer multiplicative-error loop, following adjust_lsq_mult.py logic,
    W_i = 1 / (c_v_i * |theta_hat_i|), with practical theta/weight caps.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, Iterable, List, Optional, Sequence, Tuple

import numpy as np
import scipy.sparse as sp
import cvxpy as cp
from scipy.stats.distributions import chi2


_EPS = np.finfo(float).eps
_W_MIN = 2.0 * np.sqrt(_EPS)


def _finite_summary(name: str, values: np.ndarray) -> str:
    arr = np.asarray(values, dtype=float).ravel()
    finite = arr[np.isfinite(arr)]
    if finite.size == 0:
        return f'{name}: count={arr.size}, finite=0'
    return (
        f'{name}: count={arr.size}, finite={finite.size}, '
        f'min={np.nanmin(finite):.6g}, p05={np.nanpercentile(finite, 5):.6g}, '
        f'median={np.nanmedian(finite):.6g}, p95={np.nanpercentile(finite, 95):.6g}, '
        f'max={np.nanmax(finite):.6g}'
    )


def _clip_weight_vector(W: np.ndarray, w_max: Optional[float] = None) -> np.ndarray:
    upper = np.inf if w_max is None or not np.isfinite(w_max) or w_max <= 0 else float(w_max)
    return np.clip(np.asarray(W, dtype=float), _W_MIN, upper)


